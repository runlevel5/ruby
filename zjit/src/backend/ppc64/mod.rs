    #[test]
    fn test_jmp_ptr_bytes_at_b_range_boundary() {
        // The widest branch in a 32MiB region spans 32MiB - 4 bytes, which is
        // still the largest offset a b can encode, so one instruction is enough.
        let cb = CodeBlock::new_dummy_sized(32 * 1024 * 1024);
        assert_eq!(4, cb.jmp_ptr_bytes());

        // One instruction further and a b can no longer span the region, so we
        // have to reserve room for loading an absolute address into CTR.
        let cb = CodeBlock::new_dummy_sized(32 * 1024 * 1024 + 4);
        assert_eq!(28, cb.jmp_ptr_bytes());
    }

